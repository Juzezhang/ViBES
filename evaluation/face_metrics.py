"""
Face motion metrics ported from ARTalk.
Computes LVE (Lip Vertex Error), MHD (Mean Head Distance), and FDD (Facial Dynamic Deviation)
on FLAME mesh vertices.

Reference: the metric code of ARTalk (https://github.com/xg-chu/ARTalk).
"""

import torch


def calc_val_metrics(pred_verts, gt_verts):
    """
    Compute face motion quality metrics on FLAME vertices.

    Args:
        pred_verts: [batch, seq_len, n_verts, 3] predicted vertices (meters)
        gt_verts: [batch, seq_len, n_verts, 3] ground truth vertices (meters)

    Returns:
        lve: Lip Vertex Error (mm) - max MSE on lip vertices, sqrt
        mhd: Mean Head Distance (mm) - mean MSE on all vertices, sqrt
        fdd: Facial Dynamic Deviation - temporal std difference of upper face
    """
    assert pred_verts.dim() == gt_verts.dim() == 4
    assert pred_verts.shape[-1] == gt_verts.shape[-1] == 3

    # LVE: lip vertex error
    pred_lips = pred_verts[:, :, lip_indices] * 1000  # meters to mm
    gt_lips = gt_verts[:, :, lip_indices] * 1000
    mse_dist = torch.nn.functional.mse_loss(pred_lips, gt_lips, reduction="none").sum(dim=-1)
    lve = torch.max(mse_dist, dim=-1)[0].mean().sqrt().detach()

    # MHD: mean head distance
    mse_dist_all = torch.nn.functional.mse_loss(
        pred_verts * 1000, gt_verts * 1000, reduction="none"
    ).sum(dim=-1)
    mhd = mse_dist_all.mean().sqrt().detach()

    # FDD: facial dynamic deviation
    pred_upper = pred_verts[:, :, upper_indices] * 1000
    gt_upper = gt_verts[:, :, upper_indices] * 1000
    std_pred_upper = pred_upper.sum(dim=-1).std(dim=1)
    std_gt_upper = gt_upper.sum(dim=-1).std(dim=1)
    fdd = (std_pred_upper - std_gt_upper).abs().mean().detach() * 100

    return lve, mhd, fdd


